"""Headless performance benchmark of Face-Local hot paths at multiple scales.

Measures the exact query/work patterns behind the slow UI operations
(startup sidebar refresh, Settings open, person dialog open, search,
exports, backup, save) against synthetic databases generated by
``scripts.perf_seed``.

Usage::

    python -m scripts.perf_benchmark --out test-reports/perf_report.md
    python -m scripts.perf_benchmark --quick   # small scales only

The report is a Markdown table per scale, suitable for inclusion in the
performance audit.
"""

from __future__ import annotations

import argparse
import shutil
import sqlite3
import tempfile
import time
from pathlib import Path

# (label, persons, images, faces/image)
SCALES = [
    ("100p_1k", 100, 1_000, 2.0),
    ("500p_5k", 500, 5_000, 2.0),
    ("1000p_10k", 1_000, 10_000, 2.0),
    ("5000p_50k", 5_000, 50_000, 2.0),
]
QUICK_SCALES = SCALES[:2]


def _ms(fn, *args, **kwargs):
    t0 = time.perf_counter()
    result = fn(*args, **kwargs)
    return (time.perf_counter() - t0) * 1000.0, result


def bench_startup_migrations(db_path: Path) -> float:
    """init_db on an existing DB — runs every migration check at startup."""
    import app.db.database as dbmod

    dbmod._engine = None
    dbmod._SessionFactory = None
    elapsed, _ = _ms(dbmod.init_db, db_path)
    return elapsed


def bench_sidebar_refresh_orm_graph() -> float:
    """The pre-rewrite MainWindow._refresh_persons load for comparison:
    all persons + all faces + all images as ORM entities (blobs excluded —
    they now live in face_blobs and are not loaded for this query)."""
    from sqlalchemy.orm import lazyload, selectinload

    from app.db.database import session_scope
    from app.db.models import Face, Person

    def run():
        with session_scope() as session:
            persons = (
                session.query(Person)
                .order_by(Person.name)
                .options(
                    selectinload(Person.faces)
                    .options(lazyload(Face.blob))
                    .selectinload(Face.image)
                )
                .all()
            )
            # The sidebar touches every face row (count + representative crop).
            return sum(len(p.faces) for p in persons)

    elapsed, _ = _ms(run)
    return elapsed


def bench_sidebar_refresh_lightweight() -> float:
    """The new MainWindow._refresh_persons: aggregate queries, no ORM graph."""
    from sqlalchemy import text as _sql

    from app.db.database import session_scope

    def run():
        with session_scope() as session:
            session.execute(
                _sql(
                    "SELECT id, name, is_protected, thumbnail_path "
                    "FROM persons ORDER BY name"
                )
            ).fetchall()
            session.execute(
                _sql(
                    "SELECT person_id, COUNT(*) FROM faces "
                    "WHERE person_id IS NOT NULL GROUP BY person_id"
                )
            ).fetchall()
            best_rows = session.execute(
                _sql(
                    "SELECT person_id, face_id FROM ("
                    "  SELECT f.person_id AS person_id, f.id AS face_id,"
                    "         ROW_NUMBER() OVER (PARTITION BY f.person_id"
                    "                            ORDER BY f.confidence DESC) AS rn"
                    "  FROM faces f"
                    "  WHERE f.person_id IS NOT NULL AND f.is_excluded = 0"
                    "    AND f.crop_path IS NOT NULL"
                    ") WHERE rn = 1"
                )
            ).fetchall()
            wanted = [fid for _, fid in best_rows]
            for start in range(0, len(wanted), 900):
                chunk = wanted[start:start + 900]
                placeholders = ",".join(str(int(f)) for f in chunk)
                session.execute(
                    _sql(
                        "SELECT f.id, f.person_id, f.crop_path, i.file_path,"
                        "       f.bbox_x, f.bbox_y, f.bbox_w, f.bbox_h "
                        "FROM faces f JOIN images i ON i.id = f.image_id "
                        f"WHERE f.id IN ({placeholders})"
                    )
                ).fetchall()

    elapsed, _ = _ms(run)
    return elapsed


def bench_person_list(name_filter: str = "") -> float:
    """Persons tab load / universal search."""
    from app.db.database import session_scope
    from app.services.person_service import PersonFilters, PersonService

    def run():
        with session_scope() as session:
            return len(
                PersonService(session).list_persons(PersonFilters(name=name_filter))
            )

    elapsed, _ = _ms(run)
    return elapsed


def bench_person_dialog_open() -> float:
    """The synchronous DB work PersonInfoDialog does in __init__."""
    from sqlalchemy import distinct, select

    from app.db.database import session_scope
    from app.db.models import Person, PersonGroup
    from app.services.family_service import FamilyService

    def run():
        with session_scope() as session:
            person = session.query(Person).filter(Person.id == 2).first()
            # autocomplete: 4 DISTINCT scans
            for field in ("birth_place", "death_place", "last_name", "first_name"):
                col = getattr(Person, field)
                session.execute(
                    select(distinct(col)).where(col.isnot(None)).where(col != "")
                ).scalars().all()
            # 2 family-code validations
            svc = FamilyService(session)
            if person is not None:
                try:
                    svc.ensure_unique_family_code(
                        person.family_code or "", current_person_id=person.id
                    )
                except ValueError:
                    pass
            # groups list
            session.query(PersonGroup).order_by(PersonGroup.name).all()

    elapsed, _ = _ms(run)
    return elapsed


def bench_settings_counts() -> float:
    """The synchronous DB counts SettingsDialog runs while opening."""
    from app.db.database import session_scope
    from app.db.models import Face, Image

    def run():
        with session_scope() as session:
            session.query(Image).filter(Image.relative_path.isnot(None)).count()
            session.query(Image).filter(Image.relative_path.is_(None)).count()
            session.query(Face).count()

    elapsed, _ = _ms(run)
    return elapsed


