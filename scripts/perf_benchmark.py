def bench_backup(db_path: Path, tmp: Path) -> float:
    """SQLite online backup — the safe copy used by .facepack export."""

    def run():
        src = sqlite3.connect(db_path)
        dst = sqlite3.connect(tmp / "backup.db")
        with dst:
            src.backup(dst)
        src.close()
        dst.close()

    elapsed, _ = _ms(run)
    return elapsed


def bench_save_person_edit() -> float:
    """One structured person edit (the dialog Save path)."""
    from app.db.database import session_scope
    from app.services.person_service import PersonService

    def run():
        with session_scope() as session:
            PersonService(session).update_person(2, notes=f"bench {time.time()}")

    elapsed, _ = _ms(run)
    return elapsed


BENCHES = [
    ("startup: init_db + migrations", "startup_ms"),
    ("sidebar refresh (old: full ORM graph)", "sidebar_full_ms"),
    ("sidebar refresh (new: aggregate queries)", "sidebar_light_ms"),
    ("persons tab list", "person_list_ms"),
    ("search (name filter)", "search_ms"),
    ("person dialog open (DB work)", "person_dialog_ms"),
    ("settings open (DB counts)", "settings_ms"),
    ("JSON export", "export_json_ms"),
    ("CSV export", "export_csv_ms"),
    ("DB backup (sqlite backup API)", "backup_ms"),
    ("single person edit save", "save_ms"),
]


def run_scale(label: str, persons: int, images: int, fpi: float, workdir: Path) -> dict:
    from scripts.perf_seed import seed_database

    db_path = workdir / f"perf_{label}.db"
    seed_stats = seed_database(db_path, persons, images, fpi)
    tmp = workdir / f"out_{label}"
    tmp.mkdir(exist_ok=True)

    results = {
        "label": label,
        "persons": persons,
        "images": images,
        "faces": seed_stats["faces"],
        "db_mb": seed_stats["db_mb"],
        "startup_ms": bench_startup_migrations(db_path),
        # Warm the page cache once, then take the best of 3 so the
        # comparison is not skewed by cold I/O.
        "sidebar_full_ms": min(bench_sidebar_refresh_orm_graph() for _ in range(3)),
        "sidebar_light_ms": min(bench_sidebar_refresh_lightweight() for _ in range(3)),
        "person_list_ms": bench_person_list(),
        "search_ms": bench_person_list("Kovács"),
        "person_dialog_ms": bench_person_dialog_open(),
        "settings_ms": bench_settings_counts(),
        "export_json_ms": bench_export_json(tmp),
        "export_csv_ms": bench_export_csv(tmp),
        "backup_ms": bench_backup(db_path, tmp),
        "save_ms": bench_save_person_edit(),
    }
    shutil.rmtree(tmp, ignore_errors=True)
    return results


def format_report(all_results: list[dict]) -> str:
    lines = ["# Face-Local teljesítmény-benchmark", ""]
    lines.append(
        "Szintetikus adatbázisok, service-szintű mérések (a UI-szálon futó "
        "munka pontos mása). Idők ms-ban."
    )
    lines.append("")
    header = "| művelet | " + " | ".join(r["label"] for r in all_results) + " |"
    sep = "|---" * (len(all_results) + 1) + "|"
    lines.append(
        "| skála | "
        + " | ".join(
            f"{r['persons']}p / {r['images']}img / {r['faces']}f ({r['db_mb']:.0f} MB)"
            for r in all_results
        )
        + " |"
    )
    lines.append(sep)
    lines.append(header)
    lines.append(sep)
    for title, key in BENCHES:
        row = [title] + [f"{r[key]:.0f}" for r in all_results]
        lines.append("| " + " | ".join(row) + " |")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=Path("test-reports/perf_report.md"))
    parser.add_argument("--quick", action="store_true")
    parser.add_argument("--workdir", type=Path, default=None)
    args = parser.parse_args()

    workdir = args.workdir or Path(tempfile.mkdtemp(prefix="facelocal_perf_"))
    workdir.mkdir(parents=True, exist_ok=True)

    scales = QUICK_SCALES if args.quick else SCALES
    all_results = []
    for label, persons, images, fpi in scales:
        print(f"=== {label}: seeding + benchmarking ===", flush=True)
        results = run_scale(label, persons, images, fpi, workdir)
        all_results.append(results)
        for title, key in BENCHES:
            print(f"  {title:<45} {results[key]:>9.0f} ms")

    report = format_report(all_results)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(report, encoding="utf-8")
    print(f"\nReport written to {args.out}")


if __name__ == "__main__":
    main()
